import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {makeResearchSelection} from '../src/market/researchNavigation';
const read=(file:string)=>readFileSync(file,'utf8');
assert.deepEqual(makeResearchSelection(' 00985a ','主動野村臺灣增強50'),{symbol:'00985A',name:'主動野村臺灣增強50'});
