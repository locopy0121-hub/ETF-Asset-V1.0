const app=read('App.tsx'),home=read('src/screens/HomeScreen.tsx'),market=read('src/screens/MarketResearchScreen.tsx');
assert.ok(app.includes("const [researchRequest,setResearchRequest]=useState<ResearchSelection|null>(null)"));
assert.ok(app.includes("if(active!=='market')setResearchRequest(null)"),'leaving research clears stale requested symbol');
assert.ok(app.includes("navigatePage('market');\n    setResearchRequest(selection);"),'tap must route and carry requested stock');
assert.ok(app.includes("<MarketResearchScreen initialSelection={researchRequest}/>"),'market must receive launch target');
assert.ok(app.includes("onOpenResearch={openResearch}"),'home uses actual App route');
assert.ok(home.includes("onSelect={onOpenResearch}"),'watchlist card forwards both symbol and name');
assert.ok(market.includes("useState<string|null>(initialSelection?.symbol??null)"),'research starts at selected symbol');
assert.ok(market.includes("initialSelection.symbol+' '+initialSelection.name"),'search field matches selected symbol');
assert.ok(market.includes("market.setResearchSymbols(symbol?[symbol]:[])"),'the existing canonical market subscription consumes selected symbol');
assert.ok(app.includes("setResearchRequest(null);setActive(next)"),'ordinary navigation clears any previous target');
console.log('V5.0.26 Home → Market selected watchlist routing and identity guards PASS');
