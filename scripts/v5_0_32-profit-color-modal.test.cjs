const assert=require('node:assert/strict');
const fs=require('node:fs');
const screen=fs.readFileSync('src/screens/SettingsScreen.tsx','utf8');
const picker=fs.readFileSync('src/components/ColorPalettePicker.tsx','utf8');
const app=fs.readFileSync('App.tsx','utf8');
assert.equal((screen.match(/<ProfitColorPanel\s*\/>/g)||[]).length,2,'both original settings entrypoints must remain');
assert.match(picker,/const PaletteContext=createContext/,'shared context required');
assert.match(picker,/export function ColorPaletteProvider/,'stable app-scoped native modal host required');
assert.match(picker,/active\?<ColorPalettePicker key=\{active.label\} \{\.\.\.active\} modalHost\/>/,'opened picker must mount in stable host');
assert.match(picker,/host\.open\(\{label,value,onChange,opacity,onOpacityChange,profitColorEnabled,onProfitColorChange\}\)/,'row taps must delegate to host');
assert.match(picker,/if\(modalHost\)setExpanded\(true\)/,'hosted picker must open');
assert.equal((picker.match(/if\(modalHost\)host\?\.close\(\)/g)||[]).length,2,'both Done and Cancel must close host');
assert.match(picker,/onPress=\{openPicker\}/);
assert.match(picker,/expanded\?<Modal visible/,'native Modal still required');
assert.match(picker,/onRequestClose=\{cancel\}/);
assert.match(picker,/const confirm=\(\)=>\{\s*onChange\(draft\)/);
assert.match(app,/import \{ColorPaletteProvider\}/);
assert.match(app,/<SettingsRuntimeProvider>\s*<ColorPaletteProvider>/);
assert.match(app,/<\/ColorPaletteProvider>\s*<\/SettingsRuntimeProvider>/);
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const expo=JSON.parse(fs.readFileSync('app.json','utf8')).expo;
const ci=fs.readFileSync('.github/workflows/ci.yml','utf8');
assert.match(pkg.version,/^5\.0\.\d+$/);
assert.equal(expo.version,pkg.version);
assert.equal(expo.android.versionCode,50000+Number(pkg.version.split('.')[2]));
assert.ok(ci.includes('TF-Asset-V'+pkg.version+'-QA.apk'));
console.log('V5.0.32 palette host: independent of protected Settings rerenders PASS');
