import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {candleIndexAtX} from '../src/domain/chartCrosshair';
const view=readFileSync('src/components/OfficialCandleChart.tsx','utf8');
const stock=readFileSync('src/screens/StockChartScreen.tsx','utf8');
const market=readFileSync('src/screens/MarketResearchScreen.tsx','utf8');
assert.match(stock,/<OfficialCandleChart candles=\{candles\}/);
assert.match(market,/<OfficialCandleChart key=/,'market historical chart still uses shared renderer');
assert.match(view,/<ScrollView ref=\{scrollRef\} horizontal scrollEnabled nestedScrollEnabled/);
assert.doesNotMatch(view,/scrollEnabled=\{!crosshairEnabled\}/,'crosshair ON cannot block scroll');
assert.doesNotMatch(view,/onMoveShouldSetResponder|onStartShouldSetResponder|touchOverlay/,'full-screen responder overlay must not steal swipes');
assert.match(view,/selectVisibleCandle\(scrollX\.current\)/,'panning history updates crosshair and selected values');
assert.match(view,/onPress=\{\(\)=>chooseCandle\(candle\)\}/,'tap precisely selects a K bar');
assert.match(view,/onContentSizeChange=\{\(\)=>\{/,'chart initializes scroll at latest history without truncating dates');
assert.match(view,/scrollToEnd\(\{animated:false\}\)/);
assert.match(view,/contentContainerStyle=\{\[styles\.scroll,\{width:fullWidth\}\]\}/);
assert.match(view,/referenceAxis/);
assert.match(view,/fixedCostLabel/,'fixed reference cost placed on left axis');
assert.match(view,/valueAxis/);
assert.match(view,/actualPrice/,'actual selected/latest price right axis');
assert.ok(view.indexOf('<View style={styles.referenceAxis}>')<view.indexOf('<View style={styles.viewport}'));
assert.ok(view.indexOf('<View style={styles.viewport}')<view.indexOf('<View style={styles.valueAxis}>'));
assert.match(view,/selected\?\.close|selected\.close/);
assert.doesNotMatch(view,/costLabel.*position:'absolute',left:4/,'historical horizontal scrolling cannot hide the left cost label');
for(const [x,scroll,expected] of [[12,0,0],[35,0,1],[35,36,3],[35,90,6],[10000,0,19]] as const)
  assert.equal(candleIndexAtX(x,scroll,20),expected);
assert.equal(candleIndexAtX(10,20,0),-1);
const red=readFileSync('src/domain/candleAppearance.ts','utf8');
assert.match(red,/bodyFill:tone/,'V4.0.33 solid candle rule preserved');
const version=JSON.parse(readFileSync('app.json','utf8')).expo;
assert.equal(version.version,'4.0.34');assert.equal(version.android.versionCode,40034);
const settings=readFileSync('src/screens/SettingsScreen.tsx','utf8');
assert.doesNotMatch(settings,/referenceAxis|actualPrice|selectVisibleCandle/);
assert.doesNotMatch(readFileSync('src/finance/FinanceRuntime.tsx','utf8'),/referenceAxis|actualPrice|selectVisibleCandle/);
console.log('V4.0.34 chart fixed left references, right actual labels, ON-mode swiping, full history and shared all-App chart PASS');
