import assert from 'node:assert/strict';
import {DEFAULT_MONITOR_CONFIG} from '../src/monitor/monitorDomain';
import {appendMonitorWatchlist,changeMonitorQuoteSource} from '../src/monitor/monitorListUpdates';
import {buildDividendDayAgenda} from '../src/dividend/dividendCalendar';
import type {DividendPlan} from '../src/dividend/dividendPlans';
const custom={...DEFAULT_MONITOR_CONFIG,quoteListSource:'all' as const,selectedSymbols:['2330'],normalWallLayout:{...DEFAULT_MONITOR_CONFIG.normalWallLayout,columns:2},normalWall:{...DEFAULT_MONITOR_CONFIG.normalWall,style:{...DEFAULT_MONITOR_CONFIG.normalWall.style,padding:17}},sort:{...DEFAULT_MONITOR_CONFIG.sort,manualSymbols:['2330']}};
const original=JSON.stringify(custom);
const added=appendMonitorWatchlist(custom,['0050','0050']);
assert.deepEqual(added.selectedSymbols,['2330','0050']);
assert.deepEqual(added.sort.manualSymbols,['2330','0050']);
for(const key of Object.keys(custom) as (keyof typeof custom)[])if(key!=='selectedSymbols'&&key!=='sort')assert.deepEqual(added[key],custom[key],key+' must retain custom wall configuration');
assert.equal(JSON.stringify(custom),original);
assert.equal(appendMonitorWatchlist({...custom,quoteListSource:'holdings'},['0050']).quoteListSource,'holdings');
assert.deepEqual(appendMonitorWatchlist({...custom,selectedSymbols:[]},['0050']).selectedSymbols,[],'empty means all, not only the added symbol');
const switched=changeMonitorQuoteSource(custom,'all',['2330','0050']);
assert.deepEqual(switched.selectedSymbols,['2330','0050']);assert.deepEqual(switched.normalWall,custom.normalWall);
const date='2026-10-15';
const plans:DividendPlan[]=Array.from({length:7},(_,i)=>({id:'p'+i,symbol:'005'+i,name:'ETF'+i,status:'forecast',lastBuyDate:'2026-10-14',exDate:date,recordDate:date,paymentDate:'2026-11-01',perShareAmount:null,sharesHeld:null,note:''}));
const frozen=JSON.stringify(plans);
const agenda=buildDividendDayAgenda([],plans,date,date);
assert.equal(agenda.length,14,'agenda includes every event, without the calendar dot limit');
assert.equal(agenda.filter(x=>x.type==='recordDate').length,7);
assert.equal(buildDividendDayAgenda([],plans,'2026-10-16',date).length,0);
assert.equal(buildDividendDayAgenda([],plans,'invalid',date).length,0);
assert.equal(JSON.stringify(plans),frozen,'agenda cannot post forecast income');
console.log('V4.0.62 customized wall inheritance and complete daily dividend agenda PASS');
