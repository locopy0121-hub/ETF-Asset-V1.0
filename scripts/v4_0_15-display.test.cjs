const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
const file='src/settings/displayFormat.ts';
const moduleUnderTest={exports:{}};
if(fs.existsSync(file))new Function('require','module','exports',ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(require,moduleUnderTest,moduleUnderTest.exports);
const {formatAmount,formatPercent,formatDate,scaledFontSize}=moduleUnderTest.exports;
assert.equal(typeof formatAmount,'function','saved amount preferences need a display consumer');
const prefs={fontScale:1.2,amountDecimals:2,percentDecimals:1,thousandsSeparator:false,dateFormat:'YYYY/MM/DD'};
assert.equal(formatAmount(1234.5,prefs),'1234.50');
assert.equal(formatAmount(-1234.5,{...prefs,thousandsSeparator:true}),'-1,234.50');
