assert.equal(formatPercent(-1.234,prefs),'-1.2%');
assert.equal(formatPercent(2,{...prefs,percentDecimals:0}),'2%');
assert.equal(formatDate('2026-10-09',prefs),'2026/10/09');
assert.equal(formatDate('2026-02-30',prefs),'2026-02-30','do not invent a valid date');
assert.equal(formatDate('尚未公告',prefs),'尚未公告');
